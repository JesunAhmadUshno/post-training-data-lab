"""Follow-up studies on the Build mixture result. Standard library only.

Writes results_dose.json with four additions to the v0.5 study:
1. dose: accuracy against poison share, clean 192 plus the first k
   poison records of each source category, k = 0, 8, ..., 72.
2. ablation: separates the two flaws the poison tier carries together
   (stub output and shifted label) by changing one at a time.
3. seeds: generator seeds 0 to 9, showing the seed only permutes topic ids.
4. wilson95: 95% Wilson score intervals on the recorded accuracies.
Synthetic data only, generated by this project. No real data.
"""
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "level-1-learn"))
import generator  # noqa: E402
from generator import CATEGORIES, POISON_PER_SIGNAL_CATEGORY, generate_eval, generate_raw  # noqa: E402
from model import NaiveBayes, evaluate  # noqa: E402
from pipeline import decontaminate, exact_dedup, near_dedup, quality_filter  # noqa: E402

Z95 = 1.959963984540054
DOSE_STEPS = list(range(0, POISON_PER_SIGNAL_CATEGORY + 1, 8))


def wilson(correct, total, z=Z95):
    p = correct / total
    d = 1 + z * z / total
    centre = (p + z * z / (2 * total)) / d
    half = z * math.sqrt(p * (1 - p) / total + z * z / (4 * total * total)) / d
    return [round(max(0.0, centre - half), 6), round(min(1.0, centre + half), 6)]


def _filter(records):
    out = records
    for stage in (exact_dedup, near_dedup, quality_filter, decontaminate):
        out, _ = stage(out)
    return out


def _score(train, eval_records):
    ev = evaluate(NaiveBayes().fit(train), eval_records)
    return {"correct": ev["correct"], "total": ev["total"], "accuracy": ev["accuracy"]}


def _source_category(rec):
    """Poison p001..p288 come in blocks of 72 per source category, in CATEGORIES order."""
    return CATEGORIES[(int(rec["id"][1:]) - 1) // POISON_PER_SIGNAL_CATEGORY]


def dose(raw, eval_records):
    clean = [r for r in raw if r["tier"] == "clean"]
    poison = [r for r in raw if r["tier"] == "low_quality_poison"]
    rows = []
    for k in DOSE_STEPS:
        chosen = [r for r in poison if (int(r["id"][1:]) - 1) % POISON_PER_SIGNAL_CATEGORY < k]
        train = clean + chosen
        row = {"poison_per_category": k, "train_count": len(train),
               "poison_share": round(len(chosen) / len(train), 6)}
        row.update(_score(train, eval_records))
        rows.append(row)
    return rows


def _variant(raw, label_shift, stub_output):
    out = []
    for r in raw:
        if r["tier"] != "low_quality_poison":
            out.append(r)
            continue
        x = _source_category(r)
        r = dict(r)
        if not label_shift:
            r["category"] = x
        if not stub_output:
            topic = r["instruction"].split()[1]
            r["output"] = generator.OUTPUT_TEMPLATES[x].format(topic=topic)
        out.append(r)
    return out


def ablation(raw, eval_records):
    rows = []
    for name, shift, stub in [("stub_output_shifted_label", True, True),
                              ("stub_output_correct_label", False, True),
                              ("good_output_shifted_label", True, False)]:
        data = _variant(raw, shift, stub)
        kept = _filter(data)
        rows.append({"name": name, "label_shifted": shift, "stub_output": stub,
                     "unfiltered_train_count": len(data), "unfiltered": _score(data, eval_records),
                     "filtered_train_count": len(kept), "filtered": _score(kept, eval_records)})
    return rows


def seeds(eval_records):
    original = generator.SEED
    rows = []
    try:
        for s in range(10):
            generator.SEED = s
            raw = generate_raw()
            rows.append({"seed": s,
                         "mixture_a_correct": _score(raw, eval_records)["correct"],
                         "mixture_b_correct": _score(_filter(raw), eval_records)["correct"]})
    finally:
        generator.SEED = original
    return rows


def run_dose():
    raw = generate_raw()
    eval_records = generate_eval()
    d = dose(raw, eval_records)
    below = [r["poison_per_category"] for r in d if r["accuracy"] < 0.5]
    return {
        "dataset_label": "synthetic only, generated by this project, no real data",
        "model": "multinomial Naive Bayes over instruction tokens, alpha 1.0 (model.py)",
        "eval_count": len(eval_records),
        "dose": d,
        "first_k_below_half": below[0] if below else None,
        "ablation": ablation(raw, eval_records),
        "seeds": seeds(eval_records),
        "wilson95": {"method": "Wilson score interval, z 1.959964",
                     "mixture_a": wilson(0, 80), "mixture_b": wilson(80, 80),
                     "per_category_0_of_20": wilson(0, 20), "per_category_20_of_20": wilson(20, 20)},
    }


if __name__ == "__main__":
    results = run_dose()
    with open(os.path.join(HERE, "results_dose.json"), "w", encoding="utf-8") as fh:
        json.dump(results, fh, indent=1, sort_keys=True)
        fh.write("\n")
    print(json.dumps(results, indent=1, sort_keys=True))
