"""Run the P28 Build study and write results_build.json plus data files.

Synthetic data only, labelled synthetic in every file.
Mixture A: raw generated mix, unfiltered.
Mixture B: the same records through the Learn pipeline stages.
Both train the same Naive Bayes model; both are measured on the
same held-out synthetic eval set.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "level-1-learn"))
from generator import SEED, generate_eval, generate_raw  # noqa: E402
from model import ALPHA, NaiveBayes, evaluate  # noqa: E402
from pipeline import decontaminate, exact_dedup, near_dedup, quality_filter  # noqa: E402


def _counts(records):
    out = {}
    for r in records:
        out[r["category"]] = out.get(r["category"], 0) + 1
    return dict(sorted(out.items()))


def _tier_counts(records):
    out = {}
    for r in records:
        out[r["tier"]] = out.get(r["tier"], 0) + 1
    return dict(sorted(out.items()))


def run_build():
    raw = generate_raw()
    eval_records = generate_eval()
    after_exact, removed_exact = exact_dedup(raw)
    after_near, removed_near = near_dedup(after_exact)
    after_quality, removed_quality = quality_filter(after_near)
    filtered, removed_contam = decontaminate(after_quality)

    model_a = NaiveBayes().fit(raw)
    model_b = NaiveBayes().fit(filtered)
    eval_a = evaluate(model_a, eval_records)
    eval_b = evaluate(model_b, eval_records)

    results = {
        "dataset_label": "synthetic only, generated by this project, no real data",
        "seed": SEED,
        "model": "multinomial Naive Bayes over instruction tokens, alpha 1.0",
        "alpha": ALPHA,
        "raw_count": len(raw),
        "raw_tier_counts": _tier_counts(raw),
        "raw_label_counts": _counts(raw),
        "after_exact_dedup": len(after_exact), "removed_exact": removed_exact,
        "after_near_dedup": len(after_near), "removed_near": removed_near,
        "after_quality": len(after_quality), "removed_quality_count": len(removed_quality),
        "removed_quality_all_poison": all(i.startswith("p") for i in removed_quality),
        "after_decontamination": len(filtered), "removed_contaminated": removed_contam,
        "filtered_ids": [r["id"] for r in filtered],
        "filtered_label_counts": _counts(filtered),
        "mixture_a": {"name": "raw_unfiltered", "train_count": len(raw),
                      "label_counts": _counts(raw), "eval": eval_a},
        "mixture_b": {"name": "filtered_learn_pipeline", "train_count": len(filtered),
                      "label_counts": _counts(filtered), "eval": eval_b},
        "accuracy_delta_b_minus_a": round(eval_b["accuracy"] - eval_a["accuracy"], 6),
        "eval_count": len(eval_records),
        "eval_label_counts": _counts(eval_records),
    }
    return results, raw, eval_records


def _write_jsonl(path, records):
    with open(path, "w", encoding="utf-8") as fh:
        for rec in records:
            fh.write(json.dumps(rec, sort_keys=True) + "\n")


if __name__ == "__main__":
    results, raw, eval_records = run_build()
    with open(os.path.join(HERE, "results_build.json"), "w", encoding="utf-8") as fh:
        json.dump(results, fh, indent=1, sort_keys=True)
        fh.write("\n")
    _write_jsonl(os.path.join(HERE, "synthetic_data.jsonl"), raw)
    _write_jsonl(os.path.join(HERE, "synthetic_eval.jsonl"), eval_records)
    print(json.dumps(results, indent=1, sort_keys=True))
