#!/bin/sh
# Regenerate every data and results file from the code, then fail if any committed file changed.
set -e
cd "$(dirname "$0")"
for r in level-1-learn/run_learn.py level-2-build/run_build.py level-2-build/run_dose.py level-3-deep/run_deep.py level-3-deep/run_sweep.py; do
  python3 "$r" > /dev/null
done
git diff --exit-code -- 'level-*/*.json' 'level-*/*.jsonl'
echo "reproduce: PASS, every results and data file regenerated byte for byte"
